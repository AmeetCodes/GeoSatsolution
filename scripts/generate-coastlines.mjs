/**
 * Converts Natural Earth land polygons (via world-atlas TopoJSON) into a compact,
 * quantised coordinate stream that ships to the client.
 *
 * Output: src/lib/data/land.ts  ->  base64 Int16Array
 *   [ringVertexCount, lon0, lat0, lon1, lat1, ...]  repeated per ring
 *
 * Run with: npm run gen:land
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

const RESOLUTION = process.argv[2] ?? '50m'
const SIMPLIFY_TOLERANCE = Number(process.argv[3] ?? 0.06)

const LON_SCALE = 32767 / 180
const LAT_SCALE = 32767 / 90

/** Ramer–Douglas–Peucker simplification on [lon, lat] pairs. */
function simplify(points, tolerance) {
  if (points.length <= 2) return points

  const sqTol = tolerance * tolerance
  const keep = new Uint8Array(points.length)
  keep[0] = 1
  keep[points.length - 1] = 1

  const stack = [[0, points.length - 1]]

  while (stack.length > 0) {
    const [first, last] = stack.pop()
    let maxSqDist = 0
    let index = -1

    const [ax, ay] = points[first]
    const [bx, by] = points[last]
    const dx = bx - ax
    const dy = by - ay
    const denom = dx * dx + dy * dy

    for (let i = first + 1; i < last; i++) {
      const [px, py] = points[i]

      let t = denom === 0 ? 0 : ((px - ax) * dx + (py - ay) * dy) / denom
      t = t < 0 ? 0 : t > 1 ? 1 : t

      const cx = ax + t * dx
      const cy = ay + t * dy
      const sqDist = (px - cx) ** 2 + (py - cy) ** 2

      if (sqDist > maxSqDist) {
        maxSqDist = sqDist
        index = i
      }
    }

    if (maxSqDist > sqTol && index !== -1) {
      keep[index] = 1
      stack.push([first, index], [index, last])
    }
  }

  return points.filter((_, i) => keep[i] === 1)
}

function ringsFromGeometry(geometry) {
  const { type, coordinates } = geometry
  if (type === 'Polygon') return coordinates.slice(0, 1)
  if (type === 'MultiPolygon') return coordinates.flatMap((poly) => poly.slice(0, 1))
  return []
}

/** topojson.feature() yields a FeatureCollection for GeometryCollection sources. */
function geometriesFrom(result) {
  if (!result) return []
  if (result.type === 'FeatureCollection') return result.features.map((f) => f?.geometry).filter(Boolean)
  if (result.type === 'Feature') return [result.geometry].filter(Boolean)
  return [result]
}

const topoPath = resolve(ROOT, 'node_modules/world-atlas/land-110m.json')
const topo50Path = resolve(ROOT, `node_modules/world-atlas/land-${RESOLUTION}.json`)

let source = topoPath
try {
  readFileSync(topo50Path)
  source = topo50Path
} catch {
  /* fall back to 110m */
}

const topology = JSON.parse(readFileSync(source, 'utf8'))
const land = feature(topology, topology.objects.land)

const rawRings = geometriesFrom(land).flatMap(ringsFromGeometry)
const kept = []
let rawPoints = 0
let keptPoints = 0

for (const ring of rawRings) {
  rawPoints += ring.length
  // Strip the duplicated closing vertex; rings are re-closed at decode time.
  const open = ring[0][0] === ring[ring.length - 1][0] && ring[0][1] === ring[ring.length - 1][1]
    ? ring.slice(0, -1)
    : ring

  const simplified = simplify(open, SIMPLIFY_TOLERANCE)
  if (simplified.length < 4) continue
  kept.push(simplified)
  keptPoints += simplified.length
}

kept.sort((a, b) => b.length - a.length)

const values = new Int16Array(
  kept.reduce((total, ring) => total + 1 + ring.length * 2, 0),
)

let cursor = 0
for (const ring of kept) {
  values[cursor++] = ring.length
  for (const [lon, lat] of ring) {
    values[cursor++] = Math.round(clamp(lon, -180, 180) * LON_SCALE)
    values[cursor++] = Math.round(clamp(lat, -90, 90) * LAT_SCALE)
  }
}

function clamp(v, min, max) {
  return v < min ? min : v > max ? max : v
}

const base64 = Buffer.from(values.buffer, values.byteOffset, values.byteLength).toString('base64')

const outPath = resolve(ROOT, 'src/lib/data/land.ts')
mkdirSync(dirname(outPath), { recursive: true })

writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/generate-coastlines.mjs — do not edit by hand.\n` +
    `// Source: Natural Earth via world-atlas (public domain), ${RESOLUTION} resolution,\n` +
    `// simplified with Douglas–Peucker at ${SIMPLIFY_TOLERANCE}° and quantised to Int16.\n` +
    `//\n` +
    `// Layout: [vertexCount, lon, lat, ...] repeated for each land ring.\n\n` +
    `export const LAND_SOURCE = ${JSON.stringify(RESOLUTION)}\n` +
    `export const LAND_SIMPLIFY_TOLERANCE = ${SIMPLIFY_TOLERANCE}\n` +
    `export const LAND_RING_COUNT = ${kept.length}\n` +
    `export const LAND_VERTEX_COUNT = ${keptPoints}\n` +
    `export const LAND_ARCS_B64 =\n  '${base64}'\n`,
  'utf8',
)

console.log(
  `land@${RESOLUTION}  rings ${rawRings.length} -> ${kept.length}  ` +
    `points ${rawPoints} -> ${keptPoints}  ` +
    `bytes ${(base64.length / 1024).toFixed(1)} KiB (b64) / ${(values.byteLength / 1024).toFixed(1)} KiB (i16)`,
)

/* ---------------------------------------------------------------------------
 * Land mask — a coarse equirectangular occupancy grid used in the globe shader
 * to glow the continents from within. One byte per cell; the shader samples it
 * with linear filtering, so the blockiness sits well under the vector
 * coastlines drawn on top of it.
 * ------------------------------------------------------------------------- */

const MASK_W = Number(process.argv[4] ?? 180)
const MASK_H = Number(process.argv[5] ?? 90)

/** Even-odd point-in-polygon over every ring, with a per-ring bbox reject. */
function pointInRings(lon, lat, rings) {
  let inside = false

  for (const ring of rings) {
    if (lon < ring.bbox[0] || lon > ring.bbox[2] || lat < ring.bbox[1] || lat > ring.bbox[3]) continue

    for (let i = 0, j = ring.points.length - 1; i < ring.points.length; j = i++) {
      const [xi, yi] = ring.points[i]
      const [xj, yj] = ring.points[j]

      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
        inside = !inside
      }
    }
  }

  return inside
}

const bboxed = kept.map((points) => ({
  points,
  bbox: [
    Math.min(...points.map((p) => p[0])),
    Math.min(...points.map((p) => p[1])),
    Math.max(...points.map((p) => p[0])),
    Math.max(...points.map((p) => p[1])),
  ],
}))

const mask = new Uint8Array(MASK_W * MASK_H)
let maskCells = 0

for (let row = 0; row < MASK_H; row++) {
  const lat = 90 - ((row + 0.5) * 180) / MASK_H

  for (let col = 0; col < MASK_W; col++) {
    const lon = -180 + ((col + 0.5) * 360) / MASK_W
    if (!pointInRings(lon, lat, bboxed)) continue

    mask[row * MASK_W + col] = 255
    maskCells++
  }
}

const maskB64 = Buffer.from(mask.buffer, mask.byteOffset, mask.byteLength).toString('base64')
const maskPath = resolve(ROOT, 'src/lib/data/landMask.ts')

writeFileSync(
  maskPath,
  `// AUTO-GENERATED by scripts/generate-coastlines.mjs — do not edit by hand.\n` +
    `// Source: Natural Earth via world-atlas (public domain), ${RESOLUTION} resolution.\n` +
    `//\n` +
    `// A ${MASK_W}x${MASK_H} single-channel equirectangular land/sea occupancy grid,\n` +
    `// sampled by the globe shader. Row 0 is the north pole.\n\n` +
    `export const MASK_WIDTH = ${MASK_W}\nexport const MASK_HEIGHT = ${MASK_H}\n` +
    `export const MASK_BASE64 =\n  '${maskB64}'\n`,
  'utf8',
)

console.log(
  `land mask  ${MASK_W}x${MASK_H}  land cells ${maskCells} ` +
    `(${(100 * maskCells / mask.length).toFixed(1)}%)  bytes ${(maskB64.length / 1024).toFixed(1)} KiB (b64)`,
)

/* ---------------------------------------------------------------------------
   Hero outline — the same land polygons, decimated to a fixed vertex budget,
   projected into the globe's default view and limb-clipped. The result is a
   static SVG path that the server can inline into the hero markup, so a real
   Earth is on screen before a single byte of WebGL has been downloaded.
   ------------------------------------------------------------------------- */

const OUTLINE_SOURCE = '110m'
const OUTLINE_BUDGET = Number(process.argv[6] ?? 2600)
const OUTLINE_RADIUS = 500
const OUTLINE_CENTER = 500

/** Must stay in step with components/three/framing.ts and GlobeSurface. */
const OUTLINE_TILT_X = 0.22
const OUTLINE_START_LON = 20
const OUTLINE_SPIN_Y = (-(OUTLINE_START_LON + 90) * Math.PI) / 180
const RAD = Math.PI / 180

function toVector(lon, lat) {
  const phi = (90 - lat) * RAD
  const theta = (lon + 180) * RAD
  return [-Math.sin(phi) * Math.cos(theta), Math.cos(phi), Math.sin(phi) * Math.sin(theta)]
}

function spinY(v, a) {
  const c = Math.cos(a)
  const s = Math.sin(a)
  return [v[0] * c + v[2] * s, v[1], -v[0] * s + v[2] * c]
}

function tiltX(v, a) {
  const c = Math.cos(a)
  const s = Math.sin(a)
  return [v[0], v[1] * c - v[2] * s, v[1] * s + v[2] * c]
}

function project(v) {
  return [
    (OUTLINE_CENTER + v[0] * OUTLINE_RADIUS).toFixed(1),
    (OUTLINE_CENTER - v[1] * OUTLINE_RADIUS).toFixed(1),
  ]
}

function lerpTo(a, b, t) {
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t]
}

/**
 * Orthographic path with horizon clipping. A vertex behind the limb is
 * discarded, and a segment that straddles the horizon is cut exactly at
 * z = 0 — which, under orthographic projection, lands on the limb circle.
 */
function projectedPath(rings) {
  let d = ''

  for (const ring of rings) {
    const points = ring.map(([lon, lat]) => tiltX(spinY(toVector(lon, lat), OUTLINE_SPIN_Y), OUTLINE_TILT_X))
    let open = false

    for (let i = 0; i < points.length; i += 1) {
      const a = points[i]
      const b = points[(i + 1) % points.length]
      const aFront = a[2] > 0
      const bFront = b[2] > 0

      if (aFront && bFront) {
        if (!open) { d += `M${project(a).join(' ')}`; open = true }
        d += `L${project(b).join(' ')}`
      } else if (aFront && !bFront) {
        if (!open) { d += `M${project(a).join(' ')}`; open = true }
        d += `L${project(lerpTo(a, b, a[2] / (a[2] - b[2]))).join(' ')}`
        open = false
      } else if (!aFront && bFront) {
        d += `M${project(lerpTo(a, b, a[2] / (a[2] - b[2]))).join(' ')}`
        d += `L${project(b).join(' ')}`
        open = true
      } else {
        open = false
      }
    }

    if (open) d += 'Z'
  }

  return d
}

const outlineTopology = JSON.parse(
  readFileSync(resolve(ROOT, `node_modules/world-atlas/land-${OUTLINE_SOURCE}.json`), 'utf8'),
)
const outlineLand = feature(outlineTopology, outlineTopology.objects.land)
const outlineRaw = geometriesFrom(outlineLand).flatMap(ringsFromGeometry)

/** Decimate until the projected path fits the budget. */
let outlineRings = []
let outlineTolerance = 0.05
let outlinePoints = 0

for (let attempt = 0; attempt < 14; attempt += 1) {
  outlineRings = []
  outlinePoints = 0

  for (const ring of outlineRaw) {
    const open =
      ring[0][0] === ring[ring.length - 1][0] && ring[0][1] === ring[ring.length - 1][1]
        ? ring.slice(0, -1)
        : ring
    const simplified = simplify(open, outlineTolerance)
    if (simplified.length < 4) continue
    outlineRings.push(simplified)
    outlinePoints += simplified.length
  }

  if (outlinePoints <= OUTLINE_BUDGET) break
  outlineTolerance *= 1.4
}

const outlineD = projectedPath(outlineRings)

writeFileSync(
  resolve(ROOT, 'src/lib/data/landOutline.ts'),
  `// AUTO-GENERATED by scripts/generate-coastlines.mjs — do not edit by hand.\n` +
    `// Source: Natural Earth via world-atlas (public domain), ${OUTLINE_SOURCE} resolution,\n` +
    `// Douglas–Peucker simplified to ${outlineTolerance.toFixed(3)}° and horizon-clipped.\n` +
    `//\n` +
    `// Pre-projected for the hero globe's default view (tilt ${OUTLINE_TILT_X} rad,\n` +
    `// spin ${OUTLINE_SPIN_Y.toFixed(4)} rad) in a ${OUTLINE_CENTER * 2}x${OUTLINE_CENTER * 2}\n` +
    `// viewBox, so the hero can inline a real Earth before WebGL loads.\n\n` +
    `export const OUTLINE_SOURCE = ${JSON.stringify(OUTLINE_SOURCE)}\n` +
    `export const OUTLINE_TOLERANCE = ${outlineTolerance.toFixed(4)}\n` +
    `export const OUTLINE_VERTEX_COUNT = ${outlinePoints}\n\n` +
    `export const LAND_OUTLINE_PATH =\n  '${outlineD}'\n`,
  'utf8',
)

console.log(
  `hero outline  ${OUTLINE_SOURCE}  tol ${outlineTolerance.toFixed(3)}  ` +
    `points ${outlinePoints}/${OUTLINE_BUDGET}  rings ${outlineRings.length}  ` +
    `bytes ${(Buffer.byteLength(outlineD) / 1024).toFixed(1)} KiB`,
)

/* ---------------------------------------------------------------------------
   Hero graticule — the 15 degree reference frame for the same default view.
   Emitted as pre-projected, horizon-clipped paths so the server can inline a
   complete wireframe globe without running any projection at request time.
   ------------------------------------------------------------------------- */

const GRATICULE_STEP = 15

function graticulePath(samples) {
  const projected = samples.map(([lon, lat]) => tiltX(spinY(toVector(lon, lat), OUTLINE_SPIN_Y), OUTLINE_TILT_X))
  const fmt = (p) => `${(OUTLINE_CENTER + p[0] * OUTLINE_RADIUS).toFixed(0)} ${(OUTLINE_CENTER - p[1] * OUTLINE_RADIUS).toFixed(0)}`
  const cross = (a, b) => {
    const t = a[2] / (a[2] - b[2])
    return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, 0]
  }

  let d = ''
  let open = false

  for (let i = 0; i < projected.length - 1; i += 1) {
    const a = projected[i]
    const b = projected[i + 1]
    const aFront = a[2] > 0
    const bFront = b[2] > 0

    if (aFront && bFront) {
      if (!open) { d += `M${fmt(a)}`; open = true }
      d += `L${fmt(b)}`
    } else if (aFront && !bFront) {
      if (!open) { d += `M${fmt(a)}`; open = true }
      d += `L${fmt(cross(a, b))}`
      open = false
    } else if (!aFront && bFront) {
      d += `M${fmt(cross(a, b))}L${fmt(b)}`
      open = true
    } else {
      open = false
    }
  }

  return d
}

const graticuleMinor = []
const graticuleMajor = []

for (let lon = -180; lon < 180; lon += GRATICULE_STEP) {
  if (lon === 0) continue
  const samples = []
  for (let lat = -90; lat <= 90; lat += 3) samples.push([lon, lat])
  const d = graticulePath(samples)
  ;(lon % 90 === 0 ? graticuleMajor : graticuleMinor).push(d)
}

for (let lat = -75; lat <= 75; lat += GRATICULE_STEP) {
  if (lat === 0) continue
  const samples = []
  for (let lon = -180; lon <= 180; lon += 4) samples.push([lon, lat])
  const d = graticulePath(samples)
  ;(lat % 30 === 0 ? graticuleMajor : graticuleMinor).push(d)
}

// Equator and prime meridian: the two lines a surveyor reaches for first.
const equator = []
for (let lon = -180; lon <= 180; lon += 4) equator.push([lon, 0])
graticuleMajor.push(graticulePath(equator))

const prime = []
for (let lat = -90; lat <= 90; lat += 3) prime.push([0, lat])
graticuleMajor.push(graticulePath(prime))

const graticuleMinorD = graticuleMinor.join('')
const graticuleMajorD = graticuleMajor.join('')

writeFileSync(
  resolve(ROOT, 'src/lib/data/globeGraticule.ts'),
  `// AUTO-GENERATED by scripts/generate-coastlines.mjs — do not edit by hand.\n` +
    `// A ${GRATICULE_STEP}° graticule, pre-projected and horizon-clipped for the hero\n` +
    `// globe's default view (tilt ${OUTLINE_TILT_X} rad, spin ${OUTLINE_SPIN_Y.toFixed(4)} rad)\n` +
    `// in a ${OUTLINE_CENTER * 2}x${OUTLINE_CENTER * 2} viewBox.\n` +
    `//\n` +
    `// major holds the 90°/30° lines plus the equator and prime meridian.\n\n` +
    `export const GRATICULE_STEP = ${GRATICULE_STEP}\n\n` +
    `export const GRATICULE_MINOR_PATH =\n  '${graticuleMinorD}'\n\n` +
    `export const GRATICULE_MAJOR_PATH =\n  '${graticuleMajorD}'\n`,
  'utf8',
)

console.log(
  `hero graticule  step ${GRATICULE_STEP}°  lines ${graticuleMinor.length + graticuleMajor.length}  ` +
    `minor ${(Buffer.byteLength(graticuleMinorD) / 1024).toFixed(1)} KiB  ` +
    `major ${(Buffer.byteLength(graticuleMajorD) / 1024).toFixed(1)} KiB`,
)
